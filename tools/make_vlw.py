#!/usr/bin/env python3
"""Convert TTF fonts into anti-aliased VLW (smooth font) C arrays for M5GFX.

VLW layout (big-endian int32):
  header : glyphCount, version(11), fontSize, 0, ascent, descent
  glyphs : unicode, height, width, xAdvance, dY(top above baseline), dX(left), 0
  bitmaps: width*height 8-bit alpha per glyph, in glyph order
Glyphs must be sorted by code point. Width and xAdvance must be <= 255.

Usage: python3 make_vlw.py <fonts_dir> <out_header>
"""
import struct
import sys
import freetype

FONTS = [
    # (C name, ttf file, pixel size, characters)
    ("font_speed",  "BarlowCondensed-SemiBold.ttf", 220, "-0123456789"),
    ("font_speed_m", "BarlowCondensed-SemiBold.ttf", 300, "-0123456789"),
    ("font_label",  "Barlow-SemiBold.ttf", 22, "".join(chr(c) for c in range(32, 127)) + "°·"),
    ("font_small",  "Barlow-Medium.ttf", 18, "".join(chr(c) for c in range(32, 127)) + "°·"),
    ("font_title",  "Barlow-SemiBold.ttf", 30, "".join(chr(c) for c in range(32, 127)) + "°·"),
]


def build(path, px, chars):
    face = freetype.Face(path)
    face.set_pixel_sizes(0, px)
    ascent = face.size.ascender >> 6
    descent = -(face.size.descender >> 6)
    glyphs = []
    for ch in sorted(set(chars), key=ord):
        face.load_char(ch, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_NORMAL)
        g = face.glyph
        bm = g.bitmap
        w, h = bm.width, bm.rows
        pitch = bm.pitch
        buf = bytes(bm.buffer)
        data = bytearray()
        for r in range(h):
            data += buf[r * pitch: r * pitch + w]
        adv = (g.advance.x + 32) >> 6
        if w > 255 or adv > 255:
            raise SystemExit(f"glyph {ch!r} too wide for VLW ({w}, {adv})")
        glyphs.append((ord(ch), h, w, adv, g.bitmap_top, g.bitmap_left, bytes(data)))
    out = bytearray(struct.pack(">6i", len(glyphs), 11, px, 0, ascent, descent))
    for u, h, w, adv, dy, dx, _ in glyphs:
        out += struct.pack(">7i", u, h, w, adv, dy, dx, 0)
    for *_, data in glyphs:
        out += data
    return bytes(out)


def main():
    fonts_dir, out_path = sys.argv[1], sys.argv[2]
    lines = ["// Generated by tools/make_vlw.py from the Barlow typefaces (SIL Open Font License).",
             "// Do not edit by hand.", "#pragma once", "#include <stdint.h>", ""]
    for name, ttf, px, chars in FONTS:
        blob = build(f"{fonts_dir}/{ttf}", px, chars)
        lines.append(f"// {ttf} @ {px}px, {len(blob)} bytes")
        lines.append(f"static const uint8_t {name}[{len(blob)}] __attribute__((aligned(4))) = {{")
        for i in range(0, len(blob), 32):
            lines.append("  " + ",".join(str(b) for b in blob[i:i + 32]) + ",")
        lines.append("};")
        lines.append("")
        print(f"{name}: {len(blob)} bytes")
    with open(out_path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
